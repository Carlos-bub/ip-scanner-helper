def identificar_fabricante_e_tipo(mac):
    """Exact curated OUI lookup. A MAC alone does not establish a device category.

    Conflicting prefixes were removed from the legacy table, pending an IEEE audit.
    Locally administered addresses include VMs and private Wi-Fi addresses alike.
    """
    import re

    if not mac or mac == "Desconhecido":
        return "Desconhecido", "Dispositivo não identificado"
    clean = mac.upper().replace("-", ":")
    if not re.fullmatch(r"(?:[0-9A-F]{2}:){5}[0-9A-F]{2}", clean):
        return "Desconhecido", "Dispositivo não identificado"
    first = int(clean[:2], 16)
    if first & 1 or clean == "00:00:00:00:00:00":
        return "Endereço MAC inválido para host", "Dispositivo não identificado"
    if first & 2:
        return "MAC local / privado (fabricante indeterminado)", "Dispositivo não identificado"
    if clean[:8] in OUI_DATABASE:
        return OUI_DATABASE[clean[:8]], "Dispositivo não identificado"
    return "Fabricante Não Mapeado", "Dispositivo não identificado"
