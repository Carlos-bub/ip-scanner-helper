"""Contracts supplied by infrastructure at the application's composition root."""

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from threading import Event
from typing import Protocol

from ip_scanner_helper.domain.interfaces import LocalInterface


class NetworkProbe(Protocol):
    def carregar_arp_cache(self) -> dict[str, str]: ...
    def obter_mac_e_presenca_windows(self, ip: str) -> tuple[str | None, bool]: ...
    def ping_measurement(self, ip: str) -> tuple[bool, float | str | None]: ...
    def scan_ports(self, ip: str, *, cancel_event: Event) -> list[str]: ...
    def query_snmp(self, ip: str, *, custom_community: str) -> tuple[str | None, str | None, str | None]: ...
    def query_dns_ptr(self, ip: str) -> str | None: ...
    def query_netbios(self, ip: str) -> str | None: ...
    def query_pjl_printer_model(self, ip: str) -> str | None: ...
    def query_onvif_ws_discovery(self, ip: str) -> str | None: ...
    def query_http_title(self, ip: str, *, ports: tuple[int, ...]) -> tuple[str | None, int | None]: ...
    def query_sip_voip(self, ip: str) -> str | None: ...
    def query_rdp_hostname(self, ip: str) -> str | None: ...
    def query_ssh_banner(self, ip: str) -> str | None: ...
    def query_ftp_banner(self, ip: str) -> str | None: ...
    def query_ssl_certificate(self, ip: str, *, ports: tuple[int, ...]) -> tuple[str | None, int | None]: ...
    def query_ssdp_device(self, ip: str) -> str | None: ...


class SwitchMapper(Protocol):
    def mapear_switch(self, ip: str, community: str, devices: list[dict]) -> list[dict]: ...
    def mapear_por_texto(self, text: str, devices: list[dict]) -> list[dict]: ...
    def mapear_por_telnet(self, ip: str, user: str, password: str, port: int, devices: list[dict]) -> list[dict]: ...


@dataclass(frozen=True)
class DesktopServices:
    """Explicit desktop capabilities; constructing this object performs no I/O."""

    discover_interfaces: Callable[[], list[LocalInterface]]
    export_csv: Callable[[str | Path, list[dict]], None]
    export_json: Callable[[str | Path, list[dict]], None]
    render_map: Callable[[list[dict], str | None], str]
    switch_mapper: SwitchMapper
