"""Contracts supplied by infrastructure at the application's composition root."""

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from threading import Event
from typing import Protocol

from ip_scanner_helper.domain.interfaces import LocalInterface
from ip_scanner_helper.domain.preferences import Preferences
from ip_scanner_helper.domain.credentials import SnmpCredential
from ip_scanner_helper.application.timing import DEFAULT_TIMEOUTS, ProbeContext


class NetworkProbe(Protocol):
    def carregar_arp_cache(self) -> dict[str, str]: ...
    def obter_mac_e_presenca_windows(self, ip: str, *, context: ProbeContext | None = None) -> tuple[str | None, bool]: ...
    def ping_measurement(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.icmp, context: ProbeContext | None = None) -> tuple[bool, float | str | None]: ...
    def scan_ports(self, ip: str, *, ports: dict[int, str] | None = None, cancel_event: Event, timeout: float = DEFAULT_TIMEOUTS.tcp, context: ProbeContext | None = None) -> list[str]: ...
    def query_snmp(self, ip: str, *, custom_community: str, timeout: float = DEFAULT_TIMEOUTS.snmp, context: ProbeContext | None = None) -> tuple[str | None, str | None, str | None]: ...
    def query_dns_ptr(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.dns_ptr, context: ProbeContext | None = None) -> str | None: ...
    def query_netbios(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.netbios, context: ProbeContext | None = None) -> str | None: ...
    def query_pjl_printer_model(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.pjl, context: ProbeContext | None = None) -> str | None: ...
    def query_onvif_ws_discovery(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.onvif, context: ProbeContext | None = None) -> str | None: ...
    def query_http_title(self, ip: str, *, ports: tuple[int, ...], timeout: float = DEFAULT_TIMEOUTS.http, context: ProbeContext | None = None) -> tuple[str | None, int | None]: ...
    def query_sip_voip(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.sip, context: ProbeContext | None = None) -> str | None: ...
    def query_rdp_hostname(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.rdp, context: ProbeContext | None = None) -> str | None: ...
    def query_ssh_banner(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.ssh, context: ProbeContext | None = None) -> str | None: ...
    def query_ftp_banner(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.ftp, context: ProbeContext | None = None) -> str | None: ...
    def query_ssl_certificate(self, ip: str, *, ports: tuple[int, ...], timeout: float = DEFAULT_TIMEOUTS.tls, context: ProbeContext | None = None) -> tuple[str | None, int | None]: ...
    def query_ssdp_device(self, ip: str, *, timeout: float = DEFAULT_TIMEOUTS.ssdp, context: ProbeContext | None = None) -> str | None: ...


class SwitchMapper(Protocol):
    def mapear_switch(self, ip: str, community: str, devices: list[dict], *, context: ProbeContext | None = None) -> list[dict]: ...
    def mapear_por_texto(self, text: str, devices: list[dict]) -> list[dict]: ...
    def mapear_por_telnet(self, ip: str, user: str, password: str, port: int, devices: list[dict]) -> list[dict]: ...


class L2Discovery(Protocol):
    def collect(self, ip: str, community: str, *, context: ProbeContext) -> dict: ...


class PreferencesStore(Protocol):
    read_only: bool
    message: str

    def load(self) -> Preferences: ...
    def save(self, preferences: Preferences) -> None: ...


class CredentialVault(Protocol):
    def list_credentials(self) -> list[dict]: ...
    def resolve(self, identifier: str) -> SnmpCredential: ...
    def save_credential(self, identifier: str, name: str, community: str, environment: str = "") -> str: ...
    def delete_credential(self, identifier: str) -> None: ...


class SecretProtector(Protocol):
    def protect(self, plaintext: bytes) -> bytes: ...
    def unprotect(self, ciphertext: bytes) -> bytes: ...


@dataclass(frozen=True)
class DesktopServices:
    """Explicit desktop capabilities; constructing this object performs no I/O."""

    discover_interfaces: Callable[[], list[LocalInterface]]
    export_csv: Callable[[str | Path, list[dict]], None]
    export_json: Callable[[str | Path, list[dict]], None]
    render_map: Callable[[list[dict], str | None], str]
    switch_mapper: SwitchMapper
    export_diagram: Callable[[str | Path, list[dict], str | None, str], None]
    l2_collector: L2Discovery | None = None
