"""Persistence contract; connections and migrations belong to infrastructure."""

from typing import Protocol


class HistoryStore(Protocol):
    def initialize(self) -> None: ...

    def save_session(self, snapshot: dict) -> None: ...

    def list_sessions(self, limit: int = 200) -> list[dict]: ...

    def load_session(self, session_id: str) -> dict | None: ...

    def list_reservations(self, environment_id: str) -> list[dict]: ...

    def save_reservation(self, environment_id: str, ip: str, label: str, tags: list[str]) -> None: ...

    def delete_reservation(self, environment_id: str, ip: str) -> None: ...

    def backup(self, path) -> None: ...

    def restore(self, path) -> None: ...
